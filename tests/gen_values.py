"""Writes, from the Objects tree (the template editor's picker):
  docs/values.md               every value a template can use
  docs/values-by-printer.md    which values and notifications have data
                               on the Snapmaker U1, the Creality Hi and
                               other Klipper printers
  src/pushraker/values_map.py  the same availability, for the Import
                               dialog's notices
The component runs against the tests' stand-in Moonraker with each
printer's Klipper objects (tests/fixtures/objects-*.json), without and with
Spoolman; examples come from the editor preview's sample print job.

  python3 tests/gen_values.py          write them
  python3 tests/gen_values.py --check  exit 1 when they differ (the test)
"""

import asyncio
import importlib.util
import io
import json
import os
import re
import sys
from contextlib import redirect_stdout
from typing import Any, Dict, List, Set, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PRINTERS = (("snapmaker_u1", "Snapmaker U1", "objects-snapmaker-u1.json"),
            ("creality", "Creality Hi", "objects-creality-hi.json"),
            ("generic", "Other (untested)", "objects-generic.json"))
SHORT = {"snapmaker_u1": "U1", "creality": "Hi", "generic": "Other"}
CATEGORIES = (
    ("job", "Print job (`job.*`)",
     "Generated by pushraker about the print job running (or the last one)."),
    ("event", "This notification (`event.*`)",
     "What the notification is about; which ones a notification has is "
     "listed under each."),
    ("toolheads", "Toolheads (`extruders.*`, `printer.extruder*.*`)",
     "Klipper's extruders, and what pushraker adds to them."),
    ("pushraker", "pushraker (`pushraker.*`)",
     "pushraker's settings, and what each notification sent since "
     "pushraker started."),
    ("machine", "Machine (`machine.*`)", ""),
    ("thermals", "Temperatures (`printer.*`)",
     "Klipper's own objects: any `printer.<object>.<field>` from Klipper's "
     "status reference works; these are the ones the picker lists."),
    ("fans", "Fans (`printer.*`)", "Klipper's own objects."),
)
# Examples that change from run to run (clock times, versions) or are the
# machine's own: not shown
NO_EXAMPLE = re.compile(r"^(event\.time|pushraker\.(started|version|last)|"
                        r"machine\.|job\.time\.(eta|started|sliced|end|"
                        r"clock))")
RX_CLOCK = re.compile(r"(^|\s)(\+\d+d )?\d{1,2}:\d{2}($|\s)|\d{4}-\d{2}-\d{2}")


def harness():
    spec = importlib.util.spec_from_file_location(
        "pushraker_test_harness", os.path.join(HERE, "test_pushraker.py"))
    mod = importlib.util.module_from_spec(spec)
    argv = sys.argv
    sys.argv = [argv[0]]
    try:
        with redirect_stdout(io.StringIO()):
            spec.loader.exec_module(mod)
    finally:
        sys.argv = argv
    return mod


def flatten(nodes: List[Dict[str, Any]], out: List[Dict[str, Any]]) -> None:
    for n in nodes:
        if n.get("expr"):
            out.append(n)
        flatten(n.get("children") or [], out)


def kind_of(n: Dict[str, Any]) -> str:
    if "item" in n:
        return "list"
    fmts = n.get("formats") or []
    fs = [f.get("fmt", "") for f in fmts]
    if any(re.fullmatch(r"[dDhHmM:\" ]+", f or "x") for f in fs) and \
            any(re.search(r"\d+[dhm]", f.get("label", "")) for f in fmts):
        return "duration"
    if any(":" in f.get("label", "") for f in fmts):
        return "clock time"
    if any(f in ("0", "1", "2", "3", "pct") for f in fs):
        return "number"
    return ""


async def tree(h, key: str, objects: List[str], spoolman: bool
               ) -> Tuple[Dict[str, List[Dict[str, Any]]], Any]:
    h.reset_world()
    h.STATE.clear()
    for o in objects:
        h.STATE[o] = {}
    h.STATE["print_stats"] = h.ps("standby")
    h.STATE["webhooks"] = {"state": "ready"}
    server, c = h.make({"spoolman_url": "http://spoolman:7912"}
                       if spoolman else {}, {})
    await server.handlers["server:klippy_ready"]()
    cats: Dict[str, List[Dict[str, Any]]] = {}
    for k in key:
        res = await c._ep_objects(h.WebRequest("GET", {"key": k}))
        for cat in res["categories"]:
            out: List[Dict[str, Any]] = []
            flatten(cat["children"], out)
            if cat["id"] == "event":
                for n in out:
                    n["_key"] = k
            cats.setdefault(cat["id"], []).extend(out)
    return cats, c


async def collect():
    h = harness()
    import pushraker.component as pn
    from pushraker import settings as cfg, values
    keys = [t[0] for t in cfg.TEMPLATES] + ["custom"] + [
        "custom@" + e for e in cfg.CUSTOM_EVALUATES if e != "poll"]
    # value -> {"node", "printers": {key: "yes"|"spoolman"}, "cat",
    # "events": set of notifications}
    vals: Dict[str, Dict[str, Any]] = {}
    rows: Dict[str, Dict[str, str]] = {}
    examples: Dict[str, str] = {}
    for pkey, _label, fixture in PRINTERS:
        with open(os.path.join(HERE, "fixtures", fixture)) as f:
            objects = json.load(f)
        for spoolman in (False, True):
            cats, c = await tree(h, keys, objects, spoolman)
            for cid, nodes in cats.items():
                if cid == "other":
                    continue
                for n in nodes:
                    expr = n["expr"]
                    v = vals.setdefault(expr, {"node": n, "printers": {},
                                               "cat": cid, "events": set()})
                    if "_key" in n:
                        v["events"].add(n["_key"])
                    if spoolman and pkey not in v["printers"]:
                        v["printers"][pkey] = "spoolman"
                    elif not spoolman:
                        v["printers"][pkey] = "yes"
            if not spoolman:
                p = c.printer
                gone = set(p.rows_unavailable) | set(p.missing_rows())
                for r in cfg.ROWS:
                    rid = r[0]
                    rows.setdefault(rid, {})[pkey] = (
                        "no" if rid in gone else "spoolman"
                        if rid in cfg.SPOOLMAN_ONLY else "yes")
                if pkey == "snapmaker_u1":
                    for expr, v in vals.items():
                        if v["cat"] not in ("job", "event") or \
                                NO_EXAMPLE.match(expr) or expr in examples:
                            continue
                        key = sorted(v["events"])[0] if v["events"] \
                            else "complete"
                        r = await c._ep_preview(h.WebRequest("POST", {
                            "key": key, "title": "",
                            "contents": "{{ " + expr + " }}"}))
                        text = (r.get("text") or "").strip()
                        if text and text != "n/a" and "\n" not in text \
                                and len(text) <= 60 \
                                and not RX_CLOCK.search(text):
                            examples[expr] = text
            for t in list(c._tasks):
                t.cancel()
    return vals, rows, examples, cfg, values


def md_escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def write_values_md(vals, examples) -> str:
    out = ["# Template values", "",
           "<!-- Generated by tests/gen_values.py from the Objects tree; "
           "don't edit by hand. -->", "",
           "Every value a notification's title, contents or condition can "
           "use, as the template editor's **Objects** pane lists it. A "
           "value that isn't there (no print job, a printer without that "
           "part) reads `n/a` and is false in `{% if %}`. Numbers in names "
           "(`job.filament2`, `printer.extruder1`) are per toolhead or "
           "filament. Which printers have each value: "
           "[values by printer](values-by-printer.md). The file format for "
           "a whole notification: [notification files]"
           "(notification-files.md).", ""]
    for cid, title, intro in CATEGORIES:
        items = sorted((e, v) for e, v in vals.items() if v["cat"] == cid)
        if not items:
            continue
        out += [f"## {title}", ""]
        if intro:
            out += [intro, ""]
        out += ["| Value | Kind | Example | About |", "|---|---|---|---|"]
        for expr, v in items:
            n = v["node"]
            about = " ".join(x for x in (n.get("hint", ""),
                                         n.get("info", "")) if x)
            if "item" in n:
                about += (" " if about else "") + "Each item has: " + \
                    ", ".join(f"`{i}`" for i in n["item"]) + "."
            if cid == "event":
                ev = sorted(v["events"])
                about += (" " if about else "") + "In: " + ", ".join(
                    f"`{e}`" if "@" not in e else
                    f"custom (evaluate `{e.split('@')[1]}`)"
                    for e in ev) + "." if ev else ""
            ex = examples.get(expr, "")
            out.append(f"| `{md_escape(expr)}` | {kind_of(n)} | "
                       f"{('`' + md_escape(ex) + '`') if ex else ''} | "
                       f"{md_escape(about)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def mark(state: str) -> str:
    return {"yes": "✅", "spoolman": "➖ Spoolman", "no": "❌",
            None: "❌"}[state]


def write_by_printer_md(vals, rows, cfg) -> str:
    out = ["# Values and notifications by printer", "",
           "<!-- Generated by tests/gen_values.py; don't edit by hand. -->",
           "",
           "Which notifications a printer can send, and which template "
           "values have data on it: ✅ yes, ➖ only with Spoolman, ❌ no "
           "(the value reads `n/a`). The Snapmaker U1 and Creality Hi "
           "columns are tested printers. *Other (untested)* is what the "
           "generic profile, for a Klipper printer with no profile of its "
           "own, is written to give; it hasn't been tested on a printer, "
           "and its values depend on the hardware (shown: a "
           "single-extruder printer with a heated bed, a bed mesh and Z "
           "tilt). `printer.*` values are Klipper's own "
           "and exist wherever the printer has that object.", "",
           "## Notifications", "",
           "| Notification | " + " | ".join(p[1] for p in PRINTERS) + " |",
           "|---|" + "---|" * len(PRINTERS)]
    for r in cfg.ROWS:
        rid = r[0]
        out.append(f"| {r[1]} (`{rid}`) | " + " | ".join(
            mark(rows[rid].get(p[0])) for p in PRINTERS) + " |")
    out += ["", "## Values", "",
            "| Value | " + " | ".join(SHORT[p[0]] for p in PRINTERS) + " |",
            "|---|" + "---|" * len(PRINTERS)]
    for expr in sorted(vals):
        v = vals[expr]
        if v["cat"] in ("thermals", "fans", "event"):
            continue
        cells = [mark(v["printers"].get(p[0])) for p in PRINTERS]
        out.append(f"| `{md_escape(expr)}` | " + " | ".join(cells) + " |")
    out += ["", "`event.*` values don't depend on the printer: see "
            "[values](values.md) for which notification has which.", ""]
    return "\n".join(out).rstrip() + "\n"


def write_map(vals, values) -> str:
    table: Dict[str, Set[str]] = {}
    for expr, v in vals.items():
        path = values.referenced(["{{ " + expr + " }}"])
        key = values.norm(path[0]) if path else values.norm(expr)
        table.setdefault(key, set()).update(
            p for p, s in v["printers"].items() if s)
    lines = ['# SPDX-License-Identifier: GPL-3.0-or-later',
             "# Generated by tests/gen_values.py from the Objects tree; "
             "don't edit by hand.",
             '"""Each template value pushraker knows, as values.norm() '
             'writes it, and the',
             'printer profiles that have data for it (with or without '
             'Spoolman)."""', "",
             "from typing import Dict, Tuple", "",
             "VALUES: Dict[str, Tuple[str, ...]] = {"]
    for k in sorted(table):
        lines.append(f"    {k!r}: {tuple(sorted(table[k]))!r},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    sys.path.insert(0, os.path.join(ROOT, "src"))
    vals, rows, examples, cfg, values = asyncio.run(collect())
    files = {
        os.path.join(ROOT, "docs", "values.md"): write_values_md(
            vals, examples),
        os.path.join(ROOT, "docs", "values-by-printer.md"):
            write_by_printer_md(vals, rows, cfg),
        os.path.join(ROOT, "src", "pushraker", "values_map.py"): write_map(
            vals, values),
    }
    check = "--check" in sys.argv
    bad = []
    for path, text in files.items():
        try:
            with open(path, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        if same:
            continue
        if check:
            bad.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if bad:
        print("out of date (run python3 tests/gen_values.py): "
              + ", ".join(bad))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
